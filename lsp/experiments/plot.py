"""Validate saved s=2 experiments and generate figures, CSV, and a scoreboard."""

import argparse
import csv
from decimal import Decimal, ROUND_CEILING, ROUND_FLOOR
import os
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from run import ROOT, load_case


def collect(source):
    cases = (
        [source]
        if (source / "mechanism.json").exists()
        else sorted(p.parent for p in source.glob("*/mechanism.json"))
    )
    rows = []
    for case in cases:
        mechanism, check, run = load_case(case)
        phases = run.get("phases", {})
        model = run.get("primary_model") or {}
        rows.append(
            {
                "case": case.name,
                "vertices": mechanism["v"],
                "sample_scale": 2,
                "search_cache_setting": mechanism["provenance"]["settings"].get(
                    "mem_limit"
                ),
                "primary_objective": mechanism["primary_objective"],
                "search_grid_ratio": mechanism["sampled_ratio"],
                "continuous_low": check["binsearch_apx"]["low"],
                "continuous_high": check["binsearch_apx"]["high"],
                "search_wall_seconds": phases.get("search", {}).get("wall_seconds"),
                "check_wall_seconds": phases.get("check", {}).get("wall_seconds"),
                "search_peak_rss_kib": phases.get("search", {}).get("peak_rss_kib"),
                "check_peak_rss_kib": phases.get("check", {}).get("peak_rss_kib"),
                "primary_rows": model.get("rows"),
                "primary_columns": model.get("columns"),
                "primary_elements": model.get("elements"),
            }
        )
    rows.sort(key=lambda r: r["vertices"])
    if not rows:
        raise ValueError(f"No experiments found in {source}")
    if len({r["vertices"] for r in rows}) != len(rows):
        raise ValueError("Choose one experiment per cycle size before plotting")
    return rows


def scoreboard_text(rows, source, destination):
    """Stable Markdown; round approximation endpoints outward, never inward."""
    lines = [
        "# Numerical experiment scoreboard",
        "",
        "Generated by `experiments/plot.py` from saved s=2 artifacts; do not edit the table by hand.",
        "",
        "`q` is the cycle mesh size (the `c…` directory suffix). Both approximation",
        "endpoints concern the saved candidate, not the unrestricted design problem.",
        "Endpoints are rounded outward to ten decimal places. These are floating-point",
        "checks, not exact certificates. All listed cases completed the SSP check",
        "without a reported counterexample.",
        "",
        "Times and peak RSS are approximate resource estimates, not controlled",
        "benchmarks; other processes and runtime settings may affect them. A dash",
        "means the measurement is unavailable. RSS is not total machine memory.",
        "",
        "Search cache setting is the archived `--mem-limit` value, a cache-size",
        "heuristic rather than a hard RAM cap. `Unlimited` means no limit on that",
        "cache, not unlimited machine memory. Smaller settings can trade memory",
        "for recomputation time; the checking phase is unaffected. The replay",
        "script restores these settings automatically for archived cycle sizes.",
        "",
        "| q / artifacts | Continuous lower endpoint | Continuous upper endpoint | Search time | Check time | Search peak RSS (GiB) | Check peak RSS (GiB) | Search cache setting |",
        "|--:|--:|--:|--:|--:|--:|--:|--:|",
    ]

    def duration(seconds):
        if seconds is None:
            return "—"
        return (
            f"{seconds:.1f} s"
            if seconds < 60
            else f"{seconds / 60:.1f} min"
            if seconds < 3600
            else f"{seconds / 3600:.2f} h"
        )

    def memory(kib):
        return "—" if kib is None else f"{kib / 1024**2:.2f}"

    for row in rows:
        case = source if (source / "mechanism.json").exists() else source / row["case"]
        link = Path(
            os.path.relpath(case.resolve(), destination.parent.resolve())
        ).as_posix()
        low = Decimal(str(row["continuous_low"])).quantize(
            Decimal("0.0000000001"), rounding=ROUND_FLOOR
        )
        high = Decimal(str(row["continuous_high"])).quantize(
            Decimal("0.0000000001"), rounding=ROUND_CEILING
        )
        cache = row["search_cache_setting"]
        cache_label = "Unlimited" if cache is None else f"{cache:g}"
        lines.append(
            f"| [{row['vertices']}]({link}/) | {low} | {high} | "
            f"{duration(row['search_wall_seconds'])} | {duration(row['check_wall_seconds'])} | "
            f"{memory(row['search_peak_rss_kib'])} | {memory(row['check_peak_rss_kib'])} | {cache_label} |"
        )
    return "\n".join(lines) + "\n"


def scoreboard_path(source, output):
    return (
        ROOT / "SCOREBOARD.md"
        if source.resolve() == (ROOT / "experiments/s2").resolve()
        else output / "SCOREBOARD.md"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source", type=Path, nargs="?", default=Path(__file__).parent / "s2"
    )
    parser.add_argument("--output", type=Path, default=Path("figures"))
    parser.add_argument(
        "--scoreboard", type=Path, help="Override the Markdown scoreboard destination"
    )
    args = parser.parse_args()
    rows = collect(args.source)
    args.output.mkdir(parents=True, exist_ok=True)
    scoreboard = args.scoreboard or scoreboard_path(args.source, args.output)
    scoreboard.parent.mkdir(parents=True, exist_ok=True)
    scoreboard.write_text(scoreboard_text(rows, args.source, scoreboard))
    with (args.output / "summary.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    x = [r["vertices"] for r in rows]

    def save(fig, ax, name, ylabel, title):
        ax.set(xlabel="Cycle mesh size q", ylabel=ylabel, title=title)
        ax.grid(alpha=0.25)
        ax.legend()
        for suffix in ("png", "pdf"):
            fig.savefig(args.output / f"{name}.{suffix}", dpi=180)
        plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4.5), layout="constrained")
    low = [r["continuous_low"] for r in rows]
    high = [r["continuous_high"] for r in rows]
    ax.plot(x, high, "o-", label="Numerical continuous upper endpoint")
    ax.fill_between(
        x, low, high, alpha=0.3, label="Numerical check interval (width ≤ 10⁻⁵)"
    )
    ax.plot(
        x,
        [r["search_grid_ratio"] for r in rows],
        "--",
        label="Search-grid ratio",
        alpha=0.7,
    )
    save(
        fig,
        ax,
        "approximation",
        "Approximation ratio",
        "Numerical approximation estimates (s=2)",
    )

    fig, ax = plt.subplots(figsize=(8, 4.5), layout="constrained")
    for phase in ("search", "check"):
        points = [
            (r["vertices"], r[f"{phase}_wall_seconds"])
            for r in rows
            if r[f"{phase}_wall_seconds"] is not None
        ]
        if points:
            ax.plot(*zip(*points, strict=False), "o-", label=phase.capitalize())
    ax.set_yscale("log")
    save(
        fig,
        ax,
        "runtime",
        "Wall time (seconds, log scale)",
        "Approximate runtime; uncontrolled background load",
    )

    if any(r["primary_rows"] is not None for r in rows):
        fig, ax = plt.subplots(figsize=(8, 4.5), layout="constrained")
        for metric, label in (
            ("rows", "Constraints"),
            ("columns", "Variables"),
            ("elements", "Nonzero coefficients"),
        ):
            points = [
                (r["vertices"], r[f"primary_{metric}"])
                for r in rows
                if r[f"primary_{metric}"] is not None
            ]
            ax.plot(*zip(*points, strict=False), "o-", label=label)
        ax.set_yscale("log")
        save(fig, ax, "model-size", "Count (log scale)", "Primary LP before presolve")
    print(
        f"Validated {len(rows)} experiments; wrote plots and summary.csv to {args.output}; scoreboard: {scoreboard}"
    )


if __name__ == "__main__":
    main()
